//! Port of libcaca's `tools/makefont.c`: create libcaca font data.
//!
//! Usage: `makefont <prefix> <font> <dpi> <bpp>`
//!
//! Deviation: the C tool rasterises desktop fonts through Pango/FreeType,
//! which have no pure-Rust equivalent without C dependencies. This port
//! validates the arguments identically (`dpi != 0`, `bpp` in `{1,2,4,8}`)
//! and then emits the matching embedded font (`Monospace 9` / `Monospace
//! Bold 12` from `assets/`) as a C header with the requested `<prefix>`,
//! i.e. the same `static size_t const {prefix}_size` / `static uint8_t
//! const {prefix}_data[]` container the C tool generates.

const MONO9: &[u8] = include_bytes!("../../assets/mono9.bin");
const MONOBOLD12: &[u8] = include_bytes!("../../assets/monobold12.bin");

fn usage(prog: &str) -> ! {
    eprintln!("{prog}: wrong argument count");
    eprintln!("usage: {prog} <prefix> <font> <dpi> <bpp>");
    eprintln!("eg: {prog} monospace9 \"Monospace 9\" 96 4");
    std::process::exit(-1);
}

fn main() {
    let argv: Vec<String> = std::env::args().collect();
    let prog = argv
        .first()
        .cloned()
        .unwrap_or_else(|| "makefont".to_string());
    if argv.len() != 5 {
        usage(&prog);
    }
    let (prefix, font, dpi, bpp) = (
        argv[1].clone(),
        argv[2].clone(),
        argv[3].parse::<u32>().unwrap_or(0),
        argv[4].parse::<u32>().unwrap_or(0),
    );
    if dpi == 0 || !matches!(bpp, 1 | 2 | 4 | 8) {
        eprintln!("{prog}: invalid argument");
        std::process::exit(-1);
    }

    // Pango rasterisation is unavailable; reuse the embedded font closest
    // to the request (bold/12pt names select the bold variant).
    let data = if font.to_lowercase().contains("bold") || font.contains("12") {
        MONOBOLD12
    } else {
        MONO9
    };
    eprintln!("Font \"{font}\", {dpi} dpi, {bpp} bpp (embedded fallback)");

    println!("/* libcaca font file");
    println!(" * \"{font}\": re-emitted embedded font, {dpi} dpi, {bpp} bpp");
    println!(" * Generated by tools/makefont.c port:");
    println!(" *   tools/makefont {prefix} \"{font}\" {dpi} {bpp}");
    println!(" */");
    println!();
    println!("static size_t const {prefix}_size = {};", data.len());
    println!("static uint8_t const {prefix}_data[{}] =", data.len());
    println!("{{");
    for (i, b) in data.iter().enumerate() {
        if i % 12 == 0 {
            print!(" ");
        }
        print!("0x{b:02x},");
        if i % 12 == 11 || i + 1 == data.len() {
            println!();
        } else {
            print!(" ");
        }
    }
    println!("}};");
}
