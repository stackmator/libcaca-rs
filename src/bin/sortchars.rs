//! Port of libcaca's `tools/sortchars.c`: analyse ASCII characters.
//!
//! Renders glyphs `0x20..0x7f` with the first embedded font (`Monospace 9`),
//! bins each `w*h` bitmap into a 2x3 cell grid, quantises the cells to 2
//! bits each (the `curve` table) and prints the `cells_to_ascii` /
//! `ascii_to_cells` lookup tables plus the test-circle example, exactly like
//! the C tool.

use libcaca::charset::utf32_to_utf8_array;
use libcaca::font::{font_list, load_builtin};
use libcaca::{Canvas, Color};

const GLYPHS: usize = 0x7f;
const FONT: usize = 0;
const DX: usize = 2;
const DY: usize = 3;
const RANGEBITS: u32 = 2;
const RANGE: i32 = 1 << RANGEBITS;
const FULLRANGE: usize = 1 << (RANGEBITS as usize * DX * DY);

const CURVE: [i32; 17] = [
    0, 4, 6, 8, 9, 10, 11, 12, 12, 13, 13, 14, 14, 15, 15, 15, 15,
];

fn distance(a: u16, b: u16) -> i32 {
    let mut d = 0i32;
    let mut x = a as i32;
    let mut y = b as i32;
    for _ in 0..DX * DY {
        let t = (x & (RANGE - 1)) - (y & (RANGE - 1));
        d += if t > 0 { t } else { -2 * t };
        x /= RANGE;
        y /= RANGE;
    }
    d
}

fn utf8(ch: u32) -> String {
    let (buf, n) = utf32_to_utf8_array(ch);
    String::from_utf8_lossy(&buf[..n]).into_owned()
}

fn main() -> libcaca::Result<()> {
    let fonts = font_list();
    let name = fonts.get(FONT).copied().unwrap_or_else(|| {
        eprintln!("error: libcaca was compiled without any fonts");
        std::process::exit(-1);
    });
    let f = match load_builtin(name) {
        Ok(f) => f,
        Err(_) => {
            eprintln!("error: could not load font \"{}\"", fonts[0]);
            std::process::exit(-1);
        }
    };

    let mut cv = Canvas::new(1, 1)?;
    cv.set_color_ansi(Color::White, Color::Black)?;

    let w = f.width() as usize;
    let h = f.height() as usize;
    let mut img = vec![0u8; 4 * w * h];

    let mut count = [[0i32; DY]; DX];
    for y in 0..h {
        for x in 0..w {
            count[x * DX / w][y * DY / h] += 1;
        }
    }

    let mut total = [[[0i32; DY]; DX]; GLYPHS];
    for ch in 0x20..GLYPHS as u32 {
        cv.put_char(0, 0, ch);
        f.render_canvas(&cv, &mut img, w as i32, h as i32, (4 * w) as i32)?;
        for y in 0..h * DY {
            for x in 0..w * DX {
                total[ch as usize][x / w][y / h] += img[(w * (y / DY) + (x / DX)) * 4 + 1] as i32;
            }
        }
    }

    let mut max = 0i32;
    for ch in 0x20..GLYPHS {
        for y in 0..DY {
            for x in 0..DX {
                let val = total[ch][x][y] * 256 / count[x][y];
                if val > max {
                    max = val;
                }
            }
        }
    }

    let mut allbits = [0u16; GLYPHS];
    for ch in 0x20..GLYPHS {
        let mut bits = 0i32;
        for y in 0..DY {
            for x in 0..DX {
                let t = total[ch][x][y] * 16 * 256 / (count[x][y] * max);
                bits *= RANGE;
                bits |= CURVE[t as usize] / (16 / RANGE);
            }
        }
        allbits[ch] = bits as u16;
    }

    let mut bestchar = [0u32; FULLRANGE];
    for i in 0..FULLRANGE {
        let mut mindist = 0x1000i32;
        let mut best = 0u32;
        for j in 0x20..GLYPHS as u32 {
            let d = distance(i as u16, allbits[j as usize]);
            if d < mindist {
                best = j;
                mindist = d;
                if d == 0 {
                    break;
                }
            }
        }
        bestchar[i] = best;
    }

    println!("/* Generated by sortchars.c */");
    println!("static char const cells_to_ascii[{FULLRANGE}] =");
    print!("{{    ");
    for (i, b) in bestchar.iter().enumerate() {
        print!("{b}, ");
        if i % 16 == 15 && i != FULLRANGE - 1 {
            print!("\n    ");
        }
    }
    println!("\n}};\n");
    println!("static uint16_t const ascii_to_cells[{GLYPHS}] =");
    print!("{{    ");
    for (i, b) in allbits.iter().enumerate() {
        print!("0x{b:03x}, ");
        if i % 8 == 7 && i != GLYPHS - 1 {
            print!("\n    ");
        }
    }
    println!("\n}};");

    testcircle(&bestchar);

    Ok(())
}

const WIDTH: usize = 40;
const HEIGHT: usize = 18;

fn testcircle(bestchar: &[u32; FULLRANGE]) {
    let mut buf = vec![0u8; 256 * 256];
    for y in 0..256 {
        for x in 0..256 {
            let dx = x as i32 - 128;
            let dy = y as i32 - 128;
            let dist2 = dx * dx + dy * dy;
            buf[y * 256 + x] = if dist2 < 25000 && dist2 > 18000 {
                255
            } else if dist2 < 14000 && dist2 > 9000 {
                204
            } else if dist2 < 6000 && dist2 > 3000 {
                153
            } else if dist2 < 1600 && dist2 > 300 {
                102
            } else {
                0
            };
        }
    }

    let mut dst = vec![0u16; WIDTH * DX * HEIGHT * DY];
    for y in 0..HEIGHT * DY {
        for x in 0..WIDTH * DX {
            dst[y * WIDTH * DX + x] =
                buf[(y * 256 / (HEIGHT * DY)) * 256 + (x * 256 / (WIDTH * DX))] as u16
                    * RANGE as u16
                    / 256;
        }
    }

    println!("/* example:");
    for y in 0..HEIGHT {
        for x in 0..WIDTH {
            let mut bits = 0u16;
            for j in 0..DY {
                for i in 0..DX {
                    bits *= RANGE as u16;
                    bits |= dst[(y * DY + j) * WIDTH * DX + x * DX + i];
                }
            }
            print!("{}", utf8(bestchar[bits as usize]));
        }
        println!();
    }
    println!("*/");
}
